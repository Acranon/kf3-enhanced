#!/usr/bin/env python3
"""Write patches/Map/CreatureNames.cs from data/item_t_text_all.json.

ITEM.T's profile images (the Truth Glass, 2026-10-08) run in creature-type order with
gaps for types that have none, so the offset steps:
  people 0x00..0x2B -> 77 + type   (Christy 0x00 .. James Seward McCain V 0x29, the
                                    Truth Glass and every name the player has given)
  0x2C..0x31        -> none
  monsters 0x32..0x71 -> 71 + type (Skeletons 0x3C, Race -- the ghosts -- 0x43,
                                    Statue of the Hero 0x6F)
  0x74              -> 185 Green Slime (the slimes, tests/saves/slimes.kfstate)
The first line of each decoded image is the name. The table in the game that maps
them was not found; a new area's monsters are worth checking against the Truth Glass.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
text = json.loads((ROOT / "data/item_t_text_all.json").read_text(encoding="utf-8"))

def image(t):
    if t <= 0x2B: return 77 + t
    if 0x32 <= t <= 0x71: return 71 + t
    if t == 0x74: return 185
    return None

names = {}
for t in range(0x100):
    img = image(t)
    lines = text.get(str(img)) if img is not None else None
    if not lines:
        continue
    name = lines[0].strip()
    if "¤" in name or not name:
        continue
    # Two-line titles ("Jean Alfred Forester, the" / "Swordsmaster").
    if name.endswith(",") or name.endswith(" the"):
        name += " " + lines[1].strip()
    names[t] = name

out = ["// Generated by scripts/gen_creature_names.py from data/item_t_text_all.json -- do not edit.",
       "namespace KfIII;", "",
       "/// <summary>Creature names by type, from the game's own profiles (ITEM.T image",
       "/// 77 + type, what the Truth Glass shows).</summary>",
       "public static class CreatureNames", "{",
       "    public static readonly Dictionary<int, string> ByType = new()", "    {"]
for t, n in names.items():
    out.append(f'        [0x{t:02X}] = "{n.replace(chr(34), chr(39))}",')
out += ["    };", "}", ""]
(ROOT / "patches/Map/CreatureNames.cs").write_text("\n".join(out), encoding="utf-8")
print(f"{len(names)} names, types 0x00..0x{max(names):02X}")
